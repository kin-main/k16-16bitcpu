/*==============================================================================
 * モジュール名 : uart
 * 概要         : 24ビットデータ変化検知付き UART 送信ラッパーモジュール
 * 
 * 【使い方・仕様】
 * 1. indata に送信したい24ビットデータを入力します。
 * 2. indata の値が変更され、かつ UART がアイドル状態 (!busy) になると、
 *    自動的に1クロック幅の start パルスを出力し、下位モジュールへ送信指示を出します。
 * 3. busy 中に indata がさらに変化した場合、busy が解除 (1'b0) された瞬間に
 *    最新の indata が自動送信されます。
 *
 * 【注意事項・前提条件】
 * - indata が外部スイッチ等の非同期信号の場合、上位層でメタスタビリティ対策
 *   (2段FF等) を行ってから本モジュールに入力してください。
 * - 電源投入/リセット解除時、indata が 24'd0 以外の場合は初期値として
 *   自動で1回目の送信が行われます。
 * - 下位モジュール (uart_tx_24bit) は start 入力後、即座 (同一クロック内) に
 *   busy を 1 にアサートする仕様である必要があります。
 *============================================================================*/

module uart (
    input  wire        clk,      // システムクロック
    input  wire        rst_n,    // 非同期リセット (Lowアクティブ)
    input  wire [23:0] indata,   // 送信データ入力 (24bit)
    output wire        uart_tx   // UART 送信ピン出力
);

    // 内部レジスタ・シグナル
    reg  [23:0] data;            // 直前に送信指示を出したデータ保持レジスタ
    reg         start;           // 送信開始パルス (1クロック周期幅)

    wire        busy;            // 送信中フラグ (1: 送信中, 0: アイドル)
    wire        done;            // 送信完了パルス

    //--------------------------------------------------------------------------
    // 24bit UART 送信コアのインスタンス化
    //--------------------------------------------------------------------------
    uart_tx_24bit uart_tx_inst (
        .clk   (clk),
        .rst_n (rst_n),
        .data  (data),
        .start (start),
        .tx    (uart_tx),
        .busy  (busy),
        .done  (done)
    );

    //--------------------------------------------------------------------------
    // 送信トリガー制御ロジック
    //--------------------------------------------------------------------------
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            data  <= 24'd0;
            start <= 1'b0;
        end else begin
            // start パルスはデフォルトで毎クロック 0 にクリア (1クロック幅パルスの生成)
            start <= 1'b0;

            // UARTが空き状態 (!busy) かつ 送信保留中の新しいデータがある (indata != data) 場合にキック
            if (!busy && (indata != data)) begin
                data  <= indata; // 送信データを確定・保持
                start <= 1'b1;  // 送信開始パルスを出力
            end
        end
    end

endmodule
